--  הבעיה: מסך התוכניות מציג מקטע «תוכניות הקהילה» וכפתור «שתף לקהילה»,
--  אבל על training_plans יש מדיניות RLS אחת בלבד — plans_all_own —
--  שמתירה הכול אך ורק לבעלים. כלומר המסד מחזיר לכל מאמן רק את התוכניות
--  של עצמו, ומקטע «הקהילה» הראה בפועל רק את התוכניות שהוא עצמו סימן
--  «משותף». אותו דבר ב-plan_items: בלי גישה לפריטים, «צפה כמערך אימון»
--  ו«העתק אליי» על תוכנית של מאמן אחר היו טוענים מערך ריק.
--
--  הקובץ מוסיף is_public לתוכניות (אם עוד אין) ומדיניות קריאה לתוכניות
--  משותפות ולפריטים שלהן. אידמפוטנטי — אפשר להריץ שוב בלי נזק.
--
--  ⚠ לפני ההרצה — בדוק כמה תוכניות ייחשפו ברגע שהמדיניות נכנסת:
--      select count(*) from public.training_plans where is_public;
--  אם העמודה כבר קיימת עם ברירת מחדל true, כל התוכניות הקיימות יהפכו
--  גלויות לכל המאמנים. אם המספר מפתיע — עצור, ונקה קודם:
--      update public.training_plans set is_public = false;
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1) עמודת השיתוף
--    ברירת מחדל false — בניגוד ל-drills. שום תוכנית קיימת לא הופכת
--    לציבורית מעצם ההרצה; רק «שתף לקהילה» באפליקציה מפרסם.
-- ---------------------------------------------------------------------
alter table public.training_plans
  add column if not exists is_public boolean not null default false;


-- ---------------------------------------------------------------------
-- 2) קריאת תוכניות משותפות
--    plans_all_own נשארת כמו שהיא (יצירה/עריכה/מחיקה — רק הבעלים).
--    שתי מדיניות permissive מתאחדות ב-OR, ולכן קריאה תותר אם התוכנית
--    שלי *או* שהיא משותפת. הרשאות הכתיבה לא זזות: מאמן אחר לא יכול
--    לערוך, למחוק או לבטל שיתוף של תוכנית שאינה שלו.
-- ---------------------------------------------------------------------
drop policy if exists "plans_select_public" on public.training_plans;
create policy "plans_select_public"
  on public.training_plans for select
  to authenticated
  using (is_public);


-- ---------------------------------------------------------------------
-- 3) קריאת הפריטים של תוכנית משותפת
--    בלי זה «צפה כמערך אימון» ו«העתק אליי» מקבלים תוכנית ריקה.
--    התרגילים עצמם כבר מכוסים ב-drills_select_public_or_own, והאפליקציה
--    מפרסמת תרגילים פרטיים שבתוכנית רק אחרי אישור מפורש של המאמן.
-- ---------------------------------------------------------------------
drop policy if exists "plan_items_select_public" on public.plan_items;
create policy "plan_items_select_public"
  on public.plan_items for select
  to authenticated
  using (
    exists (
      select 1 from public.training_plans p
      where p.id = plan_items.plan_id and p.is_public
    )
  );


-- ---------------------------------------------------------------------
-- 4) רענון סכימת ה-API + רישום בלדג'ר
-- ---------------------------------------------------------------------
notify pgrst, 'reload schema';
select public.mark_migration('supabase_plans_community.sql');

